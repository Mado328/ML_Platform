from .models.classifiers.nb import MultinomialNB
from .models.classifiers.knn import KNN

def main() -> None:
        # Обучающие сообщения — примеры, по которым модель учится.
    xs = [
        "вы выиграли приз нажмите сюда",
        "получите бесплатный подарок",
        "срочное предложение выигрыш приз",
        "давай встретимся сегодня вечером",
        "напомни купить молоко",
        "спасибо за помощь с проектом",
    ]

    # Правильная метка класса для каждого сообщения из xs.
    # Важно: порядок меток должен соответствовать порядку сообщений.
    labels = [
        "спам", "спам", "спам",
        "обычное", "обычное", "обычное",
    ]

    # Создаём классификатор со сглаживанием Лапласа alpha=1.
    model = MultinomialNB()

    # Обучаем его на сообщениях и соответствующих метках.
    model.fit(xs, labels)

    print(model.get_params())

    # Проверяем классификатор на новых сообщениях,
    # которых не было в обучающем наборе.
    for message in [
        "вы получили бесплатный приз",
        "давай сегодня обсудим проект",
    ]:
        print(f"Сообщение: {message}")

        # Печатаем класс с наибольшей оценённой вероятностью.
        print(f"Класс: {model.predict(message)}")

        # Печатаем оценки для всех классов.
        # Это вероятности модели, а не обязательно идеально откалиброванные
        # оценки уверенности.
        print(f"Вероятности: {model.predict_proba(message)}")
        print()
